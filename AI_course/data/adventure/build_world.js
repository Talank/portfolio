#!/usr/bin/env node
/* story.js + the lesson quizzes  ->  world.js, the one file the game loads.
 *
 * The questions are NOT written in story.js. Every lesson already ships a quiz
 * in data/lessons/<id>.js, hand-written alongside the lesson it belongs to, and
 * copying those into the game would leave two versions of the same question to
 * keep true. So they are merged here instead, at build time.
 *
 * Only the fields the game actually draws are copied across, and the lesson
 * files themselves are never shipped to the game page — they are 1.6 MB, and
 * the game needs about a tenth of that.
 *
 *   node build_world.js        # -> world.js
 */
'use strict';

const fs = require('fs');
const path = require('path');

const HERE = __dirname;
const DATA = path.resolve(HERE, '..');

global.window = {};
require(path.join(DATA, 'schedule.js'));
require(path.join(HERE, 'story.js'));

const SCHEDULE = global.window.SCHEDULE;
const STORY = global.window.MOOMIN_STORY;

const lessonIds = SCHEDULE.filter(m => m.type === 'lesson').map(m => m.id);
lessonIds.forEach(id => require(path.join(DATA, 'lessons', id + '.js')));
const LESSONS = global.window.LESSONS;

/* --- checks worth failing the build over ------------------------------- */
const placed = [];
STORY.regions.forEach(r => r.npcs.forEach(n => placed.push(n.lesson)));

const missing = lessonIds.filter(id => placed.indexOf(id) < 0);
if (missing.length) {
  console.error('lessons with nowhere to stand in the valley:\n  ' + missing.join('\n  '));
  process.exit(1);
}
placed.forEach(id => {
  if (id.charAt(0) === '@') return;                       // endgame, not a lesson
  if (lessonIds.indexOf(id) < 0) {
    console.error('npc placed for unknown lesson: ' + id);
    process.exit(1);
  }
  if (!STORY.scenes[id]) {
    console.error('no scene written for: ' + id);
    process.exit(1);
  }
});

/* --- build --------------------------------------------------------------- */
const scenes = {};
let questionCount = 0;

Object.keys(STORY.scenes).forEach(id => {
  const s = STORY.scenes[id];
  const out = { hook: s.hook, teach: s.teach, done: s.done, q: [] };

  if (id.charAt(0) !== '@') {
    const L = LESSONS[id];
    out.title = L.title;
    out.part = L.category;
    (L.quiz || []).forEach(q => {
      out.q.push({ q: q.q, o: q.options, c: q.correct, e: q.explain });
      questionCount++;
    });
    if (!out.q.length) {
      console.error('no quiz to draw questions from: ' + id);
      process.exit(1);
    }
  } else {
    /* The Groke asks questions from everywhere, so she stores none of her own —
       the game pools them from the scenes already in this file. */
    out.title = 'The Groke’s Circle';
    out.part = 'Review';
    out.pool = true;
  }
  scenes[id] = out;
});

const world = {
  cast: STORY.cast,
  reactions: STORY.reactions,
  regions: STORY.regions,
  scenes: scenes,
};

const out = path.join(HERE, 'world.js');
fs.writeFileSync(out,
  '/* GENERATED by build_world.js — do not edit by hand.\n' +
  '   story.js (the writing) merged with each lesson’s own quiz (the questions).\n' +
  '   Re-run after editing either. */\n' +
  'window.MOOMIN_WORLD = ' + JSON.stringify(world) + ';\n', 'utf8');

const kb = (fs.statSync(out).size / 1024).toFixed(1);
console.log(`world.js: ${STORY.regions.length} regions, ${placed.length} keepers, ` +
            `${questionCount} questions, ${kb} KB`);
